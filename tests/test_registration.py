import re
from pathlib import Path

from werkzeug.security import check_password_hash

import database.db as db

VALID = {"name": "Asha Rao", "email": "asha@example.com", "password": "longenough1",
         "confirm_password": "longenough1"}


def user_count():
    conn = db.get_db()
    try:
        return conn.execute("SELECT COUNT(*) FROM users").fetchone()[0]
    finally:
        conn.close()


def test_get_register_renders_form(client):
    response = client.get("/register")
    html = response.get_data(as_text=True)
    assert response.status_code == 200
    for field in ("name", "email", "password", "confirm_password"):
        assert f'name="{field}"' in html
    assert 'action="/register"' in html  # generated by url_for('register')


def test_valid_registration_creates_user_and_redirects(client):
    before = user_count()
    response = client.post("/register", data=VALID)
    assert response.status_code == 302
    assert response.headers["Location"].endswith("/login")
    assert user_count() == before + 1


def test_password_is_hashed(client):
    client.post("/register", data=VALID)
    row = db.get_user_by_email(VALID["email"])
    assert row["password_hash"] != VALID["password"]
    assert check_password_hash(row["password_hash"], VALID["password"])


def test_duplicate_email_rejected(client):
    before = user_count()
    for email in ("demo@spendly.com", "Demo@Spendly.com"):
        response = client.post("/register", data={**VALID, "email": email})
        assert response.status_code == 200
        assert "auth-error" in response.get_data(as_text=True)
    assert user_count() == before


def test_invalid_input_rejected(client):
    before = user_count()
    bad_inputs = [
        {**VALID, "name": "   "},
        {**VALID, "email": ""},
        {**VALID, "email": "foo"},
        {**VALID, "email": "@example.com"},
        {**VALID, "password": "short", "confirm_password": "short"},
        {**VALID, "confirm_password": "different123"},
        {**VALID, "confirm_password": ""},
    ]
    for data in bad_inputs:
        response = client.post("/register", data=data)
        assert response.status_code == 200
        assert "auth-error" in response.get_data(as_text=True)
    assert user_count() == before


def test_failed_submission_repopulates_without_password(client):
    data = {**VALID, "password": "short", "confirm_password": "short"}
    html = client.post("/register", data=data).get_data(as_text=True)
    assert 'value="Asha Rao"' in html
    assert 'value="asha@example.com"' in html
    assert "short" not in re.sub(r"Password must be[^<]*", "", html).replace("shortcut", "")


def test_password_mismatch_rejected_with_message(client):
    response = client.post("/register", data={**VALID, "confirm_password": "nope12345"})
    assert response.status_code == 200
    assert "Passwords do not match." in response.get_data(as_text=True)
    assert db.get_user_by_email(VALID["email"]) is None


def test_empty_confirmation_shows_mismatch_message(client):
    response = client.post("/register", data={**VALID, "confirm_password": ""})
    assert response.status_code == 200
    assert "Passwords do not match." in response.get_data(as_text=True)


def test_missing_confirmation_key_is_mismatch(client):
    data = {k: v for k, v in VALID.items() if k != "confirm_password"}
    before = user_count()
    response = client.post("/register", data=data)
    assert response.status_code == 200
    assert "Passwords do not match." in response.get_data(as_text=True)
    assert user_count() == before


def test_length_error_takes_precedence_over_mismatch(client):
    data = {**VALID, "password": "short", "confirm_password": "different"}
    html = client.post("/register", data=data).get_data(as_text=True)
    assert "at least 8 characters" in html
    assert "Passwords do not match." not in html


def test_email_trimmed_and_lowercased(client):
    client.post("/register", data={**VALID, "email": "  New@Example.com "})
    assert db.get_user_by_email("new@example.com") is not None


def test_missing_field_is_error_not_server_failure(client):
    before = user_count()
    response = client.post("/register", data={"name": "A", "email": "a@b.com", "confirm_password": "x"})
    assert response.status_code == 200
    assert "auth-error" in response.get_data(as_text=True)
    assert user_count() == before


def test_race_duplicate_insert_is_handled(client, monkeypatch):
    import app as app_module

    monkeypatch.setattr(app_module, "get_user_by_email", lambda email: None)
    before = user_count()
    response = client.post("/register", data={**VALID, "email": "demo@spendly.com"})
    assert response.status_code == 200
    assert "already exists" in response.get_data(as_text=True)
    assert user_count() == before


def test_app_py_has_no_sql_or_sqlite3():
    source = (Path(__file__).resolve().parent.parent / "app.py").read_text()
    assert "sqlite3" not in source
    assert not re.search(r"\b(SELECT|INSERT|UPDATE|DELETE)\b", source)
